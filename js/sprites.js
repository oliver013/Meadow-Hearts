  // ------- Renderer ---------
  // Palette can be array (indexed by 0-9 chars) or object (keyed by char).
  function drawPattern(ctx, x, y, palette, pattern) {
    const isArray = Array.isArray(palette);
    for (let row = 0; row < pattern.length; row++) {
      const line = pattern[row];
      for (let col = 0; col < line.length; col++) {
        const ch = line[col];
        if (ch === '.' || ch === '0') continue;
        let color;
        if (isArray) {
          const idx = parseInt(ch, 16);
          if (isNaN(idx)) continue;
          color = palette[idx];
        } else {
          color = palette[ch];
        }
        if (!color || color === '.') continue;
        ctx.fillStyle = color;
        ctx.fillRect(x + col, y + row, 1, 1);
      }
    }
  }

  function drawTile(ctx, name, x, y) {
    const pat = TILE_PATTERNS[name];
    const pal = TILE_PALETTES[name] || TILE_PALETTES.grass;
    if (!pat) {
      ctx.fillStyle = pal[1] || '#000';
      ctx.fillRect(x, y, TILE, TILE);
      return;
    }
    drawPattern(ctx, x, y, pal, pat);
  }

